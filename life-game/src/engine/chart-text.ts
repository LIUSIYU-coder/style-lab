/** 十神占比,合计 100 */
export function familyShares(chart: Chart): Array<{ family: Family; name: string; hint: string; pct: number }> {
  const total = Object.values(chart.families).reduce((s, v) => s + v, 0) || 1;
  return (Object.keys(FAMILY_NAME) as Family[])
    .map(f => ({ family: f, ...FAMILY_NAME[f], pct: Math.round((chart.families[f] / total) * 100) }))
    .sort((a, b) => b.pct - a.pct);
}

